<?php

declare(strict_types=1);

namespace ZeroForLaravel\Generation;

use LogicException;
use ZeroForLaravel\Query\QueryLimits;
use ZeroForLaravel\Tables\TableDefinition;
use ZeroForLaravel\Tables\TableRelationPath;

/** Emits deployable registrations; never executes an HTTP action to sample its query. */
final readonly class ControllerQueryGenerator
{
    public function __construct(private SchemaDriver $schemas) {}

    /** @param list<ControllerQuery> $queries */
    public function typescript(array $queries, string $schemaImport): string
    {
        if ($queries === []) {
            return implode("\n", [
                '// Generated by Zero for Laravel. Deploy together with the PHP registrations.',
                "import {defineQueriesWithType} from '@rocicorp/zero';",
                'import type {schema} from '.json_encode($schemaImport, JSON_THROW_ON_ERROR).';',
                'export const inputs = {};',
                'export const publicInputs = {};',
                'export const queries = defineQueriesWithType<typeof schema>()({});',
                'export const bindings = {};',
                'export const actions = {};',
                '',
            ]);
        }

        $bodies = implode("\n", array_map(static fn (ControllerQuery $query): string => $query->typescript(), $queries));
        $code = preg_replace('/"(?:[^"\\\\]|\\\\.)*"/s', '""', $bodies) ?? throw new LogicException('Cannot inspect generated query helpers.');
        $optionHelpers = str_contains($code, 'optionContains(') ? ', optionContains' : '';
        $dateHelper = str_contains($code, 'encodeDate(') ? ', encodeDate' : '';
        $lines = [
            '// Generated by Zero for Laravel. Deploy together with the PHP registrations.',
            "import {createBuilder, defineQueriesWithType, defineQueryWithType} from '@rocicorp/zero';",
            "import {liveQuery, withQueryInputs{$dateHelper}{$optionHelpers}} from '@nickwelsh/zero-for-laravel';",
            $this->schemas->imports(),
            'import {schema, definitions, type Context} from '.json_encode($schemaImport, JSON_THROW_ON_ERROR).';',
            'const zql = createBuilder(schema);',
            'const defineQueries = defineQueriesWithType<typeof schema>();',
            'const defineQuery = defineQueryWithType<typeof schema, Context>();',
        ];
        if (str_contains($code, 'pagePrefix(')) {
            $cap = QueryLimits::liveWindow();
            $lines[] = <<<TS
function pagePrefix(size: number, page = 1, window?: number) {
    if (!Number.isSafeInteger(size) || size < 1 || !Number.isSafeInteger(page) || page < 1 || page > Math.floor(({$cap} - 1) / size)) throw new RangeError('Page exceeds the live window cap.');
    const prefix = page * size + 1;
    if (window !== undefined && (!Number.isSafeInteger(window) || window < prefix || window > {$cap})) throw new RangeError('Invalid scroll window.');
    return window ?? prefix;
}
TS;
        }

        $lines[] = 'export const inputs = {';
        foreach ($queries as $query) {
            $cursor = null;
            $mode = $query->expression->kind === 'paginate' ? $query->expression->stringValue() : null;
            if ($mode === 'cursor') {
                $cursor = [];
                foreach ($query->expression->cursorFields() as $field) {
                    $column = $query->expression->model?->columns[$field];
                    $type = match ($column['type'] ?? null) {
                        'string' => 'string', 'number' => 'float', 'boolean' => 'bool',
                        default => throw new LogicException('Unsupported cursor column '.$field),
                    };
                    $cursor[$field] = ($column['nullable'] ? 'nullable:' : '').$type;
                }
            }

            $lines[] = '  '.json_encode($query->name(), JSON_THROW_ON_ERROR).': '.$this->schemas->object($query->parameters, $cursor, contracts: $query->optionContracts(), routed: $query->optionSource === null && ! $query->standalone, pagination: $mode).',';
        }

        $lines[] = '};';
        $lines[] = 'export const publicInputs = {';
        foreach ($queries as $query) {
            $lines[] = '  '.json_encode($query->name(), JSON_THROW_ON_ERROR).': '.$this->schemas->object($query->parameters, public: true, contracts: $query->optionContracts(), routed: $query->optionSource === null && ! $query->standalone).',';
        }

        $lines[] = '};';
        $lines[] = 'export const queries = defineQueries({';
        foreach ($queries as $query) {
            $name = json_encode($query->name(), JSON_THROW_ON_ERROR);
            $lines[] = '  '.$name.': defineQuery(inputs['.$name.'], '.$query->typescript().'),';
        }

        $lines[] = '});';
        $lines[] = 'export const bindings = {';
        foreach ($queries as $query) {
            $name = json_encode($query->name(), JSON_THROW_ON_ERROR);
            $parse = $this->schemas->parse('inputs['.$name.']', 'args');
            $model = json_encode($query->expression->model?->name, JSON_THROW_ON_ERROR);
            $pageSize = '';
            if ($query->expression->kind === 'paginate') {
                $mode = $query->expression->stringValue();
                $pageSize = ', '.$query->expression->children[1]->emit(true).', '.($mode === 'cursor' ? json_encode($query->expression->cursorFields(), JSON_THROW_ON_ERROR) : 'undefined')
                    .', '.QueryLimits::liveWindow().', '.json_encode(['mode' => $mode, 'name' => $query->expression->children[2]->stringValue()], JSON_THROW_ON_ERROR);
            }

            $request = null;
            $options = [];
            foreach ($query->parameters as $parameter => $type) {
                if (str_starts_with($type, 'request:')) {
                    $request = $parameter;
                    foreach (RequestContract::value(substr($type, 8))->fields as $field => $contract) {
                        if (($choices = $contract->choices()) !== null) {
                            $options[$field] = $choices;
                        }
                    }
                }
            }

            $lines[] = '  '.$name.': (args: Parameters<typeof queries['.$name.']>[0]) => withQueryInputs(liveQuery(queries['.$name.'], '.$parse.', definitions, '.$model.', '.($query->expression->singular ? 'true' : 'false').$pageSize.'), '.$parse.', '.json_encode($request, JSON_THROW_ON_ERROR).', '.json_encode((object) $options, JSON_THROW_ON_ERROR).' as const, value => '.$this->schemas->parse('inputs['.$name.']', 'value').'),';
        }

        $lines[] = '};';
        $lines[] = 'export const actions = {';
        foreach ($queries as $query) {
            $name = json_encode($query->name(), JSON_THROW_ON_ERROR);
            $action = json_encode($query->action.'.'.$query->prop, JSON_THROW_ON_ERROR);
            $lines[] = '  '.$action.': (input: '.$this->schemas->inputType('publicInputs['.$name.']').') => { const args = '.$this->schemas->parse('publicInputs['.$name.']', 'input').'; return bindings['.$name.']('.$this->schemas->encode($query->parameters, 'args').'); },';
        }

        $lines[] = '};';

        return implode("\n", $lines)."\n";
    }

    /** @param list<ControllerQuery> $queries
     * @param  list<TableDefinition>  $tables
     */
    public function php(array $queries, array $tables = []): string
    {
        $lines = ['<?php', '', 'declare(strict_types=1);', '', '// Generated by Zero for Laravel. Do not edit.', 'return ['];
        foreach ($queries as $query) {
            if ($query->optionSource !== null) {
                $source = str_replace(" => \n", " =>\n", var_export($query->optionSource, true));
                $lines[] = '    '.var_export($query->name(), true).' => new \\ZeroForLaravel\\Query\\RegisteredOptionQuery('.implode(', ', [var_export($query->action, true), var_export($query->parameters, true), $query->php(), $source, var_export($query->name(), true)]).'),';

                continue;
            }

            $contracts = [];
            foreach ($query->parameters as $name => $type) {
                if (str_starts_with($type, 'request:')) {
                    $contracts[] = var_export($name, true).' => '.RequestContract::value(substr($type, 8))->php();
                }
            }

            $lines[] = '    '.var_export($query->name(), true).' => new \\ZeroForLaravel\\Query\\RegisteredQuery('.implode(', ', [
                var_export($query->action, true), var_export($query->component, true), var_export($query->prop, true),
                var_export($query->parameters, true), $query->php(), '['.implode(', ', $contracts).']', var_export($query->guards, true), var_export($query->name(), true),
            ]).($query->standalone ? ', standalone: true' : '').'),';
        }

        foreach ($tables as $table) {
            $lines[] = '    '.var_export($table->queryName(), true).' => new \\ZeroForLaravel\\Tables\\RegisteredTableQuery('.var_export($table->name, true).', '.var_export($table->contract, true).'),';
            foreach (TableRelationPath::all($table) as $path) {
                if ($path->choices === null) {
                    continue;
                }

                foreach (['list', 'resolve'] as $operation) {
                    $bindings = array_keys(TableChoiceBindings::for($path, $operation, $queries));
                    $name = $path->queryName($table, $operation, $bindings);
                    $arguments = [$table->name, $table->contract, $operation, $path->path, $bindings, $name];
                    $lines[] = '    '.var_export($name, true).' => new \\ZeroForLaravel\\Tables\\RegisteredTableQuery('.implode(', ', array_map(static fn (string|array $value): string => var_export($value, true), $arguments)).'),';
                }
            }
        }

        $lines[] = '];';

        return str_replace(" => \n", " =>\n", implode("\n", $lines)."\n");
    }
}
