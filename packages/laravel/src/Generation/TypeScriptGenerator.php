<?php

declare(strict_types=1);

namespace ZeroForLaravel\Generation;

use LogicException;
use ZeroForLaravel\Context\ContextDefinition;
use ZeroForLaravel\Metadata\ModelMetadata;
use ZeroForLaravel\Metadata\ModelRegistry;

final class TypeScriptGenerator
{
    public function generateReact(string $contracts, string $options, string $mutations, bool $custom = false): string
    {
        $imports = "// Generated by Zero for Laravel. Edit connection options in the imported config module.\n"
            ."import {createZeroProvider} from '@nickwelsh/zero-for-laravel/react';\n"
            ."import {useZero as useNativeZero} from '@rocicorp/zero/react';\n"
            ."import type {MutationPreparation} from '@nickwelsh/zero-for-laravel';\n"
            .'import {schema, definitions, contextContract, type Context} from '.$this->json($contracts).";\n"
            .'import {createControllerMutationBindings} from '.$this->json($mutations).";\n"
            .'import {options} from '.$this->json($options).";\n"
            ."export function useZero() { return useNativeZero<typeof schema, undefined, Context>(); }\n";
        if ($custom) {
            return $imports
                ."export function createZeroBindings(projections: Parameters<typeof createControllerMutationBindings<typeof schema, Context>>[2], preparation: MutationPreparation = {}) {\n"
                ."  const {mutators, actions} = createControllerMutationBindings<typeof schema, Context>(schema, definitions, projections);\n"
                ."  const ZeroProvider = createZeroProvider<Context>(schema, mutators, options, true, {actions, preparation}, contextContract);\n"
                ."  const controllerRuntime = () => ({client: ZeroProvider.getClient(), actions, preparation});\n"
                ."  return {mutators, actions, ZeroProvider, controllerRuntime};\n"
                ."}\n";
        }

        return $imports
            ."export function createZeroBindings(preparation: MutationPreparation = {}) {\n"
            ."  const {mutators, actions} = createControllerMutationBindings<typeof schema, Context>(schema, definitions);\n"
            ."  const ZeroProvider = createZeroProvider<Context>(schema, mutators, options, true, {actions, preparation}, contextContract);\n"
            ."  const controllerRuntime = () => ({client: ZeroProvider.getClient(), actions, preparation});\n"
            ."  return {mutators, actions, ZeroProvider, controllerRuntime};\n"
            ."}\n"
            ."export const {mutators, actions, ZeroProvider, controllerRuntime} = createZeroBindings();\n";
    }

    public function generate(ModelRegistry $registry): string
    {
        $models = $registry->all();
        ksort($models);
        $tables = [];
        foreach ($models as $model) {
            // Validate deferred scopes even when no controller starts from this model.
            (new NativeQueryEmitter)->emit(new QueryExpression('query', model: $model, type: 'query'));
            $tables[$model->table] = ['columns' => $model->columns, 'key' => [$model->key]];
        }

        foreach ($registry->pivotColumns() as $table => $columns) {
            $tables[$table] = ['columns' => $columns, 'key' => $registry->pivotKeys()[$table]];
        }

        $tables += $registry->accessTables();
        ksort($tables);
        $names = [];
        foreach (array_keys($tables) as $i => $table) {
            $names[$table] = 'table'.$i;
        }

        $columns = [];
        foreach ($tables as $table) {
            array_push($columns, ...array_column($table['columns'], 'type'));
        }

        $builders = array_values(array_filter(['string', 'number', 'boolean', 'json'], static fn (string $type): bool => in_array($type, $columns, true)));
        $relationships = array_filter($models, static fn (ModelMetadata $model): bool => $model->relations !== []) !== [];
        $imports = [...($tables === [] ? [] : ['table']), ...$builders, ...($relationships ? ['relationships'] : []), 'createSchema'];
        $lines = [
            '// Generated by Zero for Laravel. Run php artisan zero:generate after model changes.',
            'import {'.implode(', ', $imports)."} from '@rocicorp/zero';",
            'import type {ContractMap'.($models === [] ? '' : ', ModelRow')."} from '@nickwelsh/zero-for-laravel';", '',
        ];
        $context = ContextDefinition::configured();
        $lines[] = 'export type Context = '.$context->typescript().';';
        $lines[] = 'export const contextContract = '.$this->json((object) $context->contract()).' as const;';
        foreach ($tables as $name => $table) {
            $lines[] = 'const '.$names[$name].' = table('.$this->json($name).').columns({';
            foreach ($table['columns'] as $field => $column) {
                $lines[] = '  '.$this->json($field).': '.$column['type'].'()'.($column['nullable'] ? '.optional()' : '').',';
            }

            $lines[] = '} ).primaryKey('.implode(', ', array_map($this->json(...), $table['key'])).');';
        }

        $schemaEdges = [];
        foreach ($models as $model) {
            $schemaEdges[$model->table] = $model->relations;
            foreach ($model->junctionLookups as $lookup) {
                if (isset($model->columns[$lookup->pivots]) || isset($tables[$lookup->pivotHop['table']]['columns'][$lookup->target])) {
                    throw new LogicException('A generated junction lookup relationship conflicts with a column.');
                }

                $schemaEdges[$model->table][$lookup->pivots] = ['cardinality' => 'many', 'path' => [$lookup->pivotHop]];
                $schemaEdges[$lookup->pivotHop['table']][$lookup->target] = ['cardinality' => 'one', 'path' => [$lookup->targetHop]];
            }
        }

        $relations = [];
        foreach (array_filter($schemaEdges) as $table => $edges) {
            $variable = $names[$table].'Relations';
            $relations[] = $variable;
            $helpers = array_intersect(['one', 'many'], array_column($edges, 'cardinality'));
            $lines[] = 'const '.$variable.' = relationships('.$names[$table].', ({'.implode(', ', $helpers).'}) => ({';
            foreach ($edges as $name => $relation) {
                $connections = [];
                foreach ($relation['path'] as $hop) {
                    $connections[] = '{sourceField: '.$this->json($hop['source']).', destField: '.$this->json($hop['dest']).', destSchema: '.$names[$hop['table']].'}';
                }

                $lines[] = '  '.$this->json($name).': '.$relation['cardinality'].'('.implode(', ', $connections).'),';
            }

            $lines[] = '}));';
        }

        $lines[] = 'export const schema = createSchema({tables: ['.implode(', ', $names).'], relationships: ['.implode(', ', $relations).'], enableLegacyQueries: false, enableLegacyMutators: false});';
        $definitions = array_map(fn (ModelMetadata $model): array => $model->toArray(), $models);
        $lines[] = 'export const definitions = '.$this->json((object) $definitions, true).' as const satisfies ContractMap;';
        foreach ($models as $model) {
            $lines[] = 'export type '.$model->name.'Row = ModelRow<typeof definitions, '.$this->json($model->name).'>;';
        }

        return implode("\n", $lines)."\n";
    }

    private function json(mixed $value, bool $pretty = false): string
    {
        return json_encode($value, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES | ($pretty ? JSON_PRETTY_PRINT : 0));
    }
}
