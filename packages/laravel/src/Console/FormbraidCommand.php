<?php

declare(strict_types=1);

namespace ZeroForLaravel\Console;

use Formbraid\Laravel\ComponentEnum;
use Formbraid\Laravel\ComponentMetadata;
use Formbraid\Laravel\Configuration;
use Formbraid\Laravel\FormEmitter;
use Formbraid\Laravel\GeneratedFiles;
use Formbraid\Laravel\RequestExtractor;
use Illuminate\Console\Command;
use Illuminate\Foundation\Http\FormRequest;
use RuntimeException;
use Throwable;
use ZeroForLaravel\Generation\ControllerDiscovery;
use ZeroForLaravel\Generation\ControllerQuery;
use ZeroForLaravel\Generation\OptionQueryCompiler;
use ZeroForLaravel\Generation\SchemaDriver;

/** Reuse Formbraid's definitions; only the controller's Zero submission callback differs. */
final class FormbraidCommand extends Command
{
    protected $signature = 'zero:formbraid';

    protected $description = 'Generate callback-backed Formbraid descriptors for Zero controller mutations';

    public function handle(ControllerDiscovery $controllers): int
    {
        try {
            if (! class_exists(ComponentMetadata::class)) {
                throw new RuntimeException('Install formbraid/laravel ^0.3.0 before generating Zero forms.');
            }

            $config = config()->array('formbraid');
            $output = GeneratedFiles::path(config('zero.formbraid_output'), 'zero output');
            $metadata = GeneratedFiles::path($config['metadata'] ?? null, 'metadata');
            $enumPath = GeneratedFiles::path($config['component_enum'] ?? null, 'component_enum');
            $components = ComponentMetadata::read(base_path($metadata));
            $enum = ComponentEnum::generate($enumPath, $components);
            $enum->load();
            $extractor = new RequestExtractor(Configuration::from($config));
            $emitter = new FormEmitter($components);
            $zero = config()->string('zero.output');
            if (str_starts_with($zero, base_path().'/')) {
                $zero = substr($zero, strlen(base_path()) + 1);
            }

            $zero = GeneratedFiles::path($zero, 'zero schema');
            $root = dirname($zero);
            $base = pathinfo($zero, PATHINFO_FILENAME);
            $runtime = config('zero.formbraid_runtime');
            $runtime ??= $root.'/'.$base.'.react.ts';
            $runtime = GeneratedFiles::path($runtime, 'zero runtime');
            $files = [$enumPath => $enum->source];
            $modules = [];
            foreach ($controllers->mutations() as $mutation) {
                $requests = array_filter($mutation->parameters, static fn (array $parameter): bool => $parameter['kind'] === 'request');
                if ($requests === []) {
                    continue;
                }

                if (count($requests) !== 1) {
                    throw new RuntimeException($mutation->action.': a form must reference exactly one FormRequest.');
                }

                if ($mutation->optimism === 'custom' && config('zero.formbraid_runtime') === null) {
                    throw new RuntimeException('Set zero.formbraid_runtime to the application module exporting controllerRuntime with custom projections.');
                }

                $requestClass = array_values($requests)[0]['type'] ?? '';
                if (! is_subclass_of($requestClass, FormRequest::class)) {
                    throw new RuntimeException($mutation->action.': invalid FormRequest.');
                }

                // Never resolve a FormRequest through the container: it would authorize/validate it.
                $request = $requestClass::createFrom(request(), new $requestClass);
                $request->setContainer(app());
                $extracted = $extractor->extract($request);
                $options = resolve(OptionQueryCompiler::class)->compile($mutation);
                $requestPath = $output.'/requests/'.FormEmitter::path($requestClass);
                $files[$requestPath] = $emitter->emit($extracted['form'], array_values(array_unique(array_map(static fn (ControllerQuery $query): string => $query->options()['id'], $options))));
                foreach ($extracted['diagnostics'] as $diagnostic) {
                    $this->warn($diagnostic);
                }

                [$controller, $method] = explode('@', $mutation->action, 2);
                $controllerPath = FormEmitter::path($controller);
                $path = $output.'/'.$controllerPath;
                $definition = '_definition_'.$method;
                $action = '_action_'.$method;
                $modules[$path] ??= [
                    '// Generated by Zero for Laravel. Edit the FormRequest or configuration.',
                    "import {createControllerForm} from '@nickwelsh/zero-for-laravel/formbraid';",
                    'import {controllerRuntime} from '.$this->import($path, $runtime).';',
                ];
                $modules[$path][] = 'import {'.FormEmitter::name($requestClass).' as '.$definition.'} from '.$this->import($path, $requestPath).';';
                $modules[$path][] = 'import {'.$method.' as '.$action.'} from '.$this->import($path, $root.'/'.$controllerPath).';';
                if ($options !== []) {
                    $modules[$path]['optionsImport'] = "import {withOptionSources} from '@formbraid/react';";
                    $modules[$path]['adapterImport'] = "import {createZeroOptionSource} from '@nickwelsh/zero-for-laravel/react/formbraid';";
                    $modules[$path]['queriesImport'] = 'import {bindings as _optionBindings, inputs as _optionInputs} from '.$this->import($path, $root.'/'.$base.'.queries.ts').';';
                    $sources = [];
                    foreach ($options as $query) {
                        $sources[$query->options()['id']][$query->options()['operation']] = $query;
                    }

                    $entries = [];
                    foreach ($sources as $id => $operations) {
                        $list = $operations['list'];
                        $metadata = $list->options();
                        $entries[] = json_encode($id, JSON_THROW_ON_ERROR).': createZeroOptionSource({value: '.json_encode($metadata['value'], JSON_THROW_ON_ERROR).', label: '.json_encode($metadata['label'], JSON_THROW_ON_ERROR).', list: '.$this->operation($list).(isset($operations['resolve']) ? ', resolve: '.$this->operation($operations['resolve']) : '').'})';
                    }

                    $modules[$path][] = 'const _options_'.$method.' = {'.implode(', ', $entries).'};';
                }

                $parameters = [];
                foreach ($mutation->parameters as $name => $parameter) {
                    if (in_array($parameter['kind'], ['model', 'scalar'], true)) {
                        $parameters[] = json_encode($name, JSON_THROW_ON_ERROR).': string | number | boolean';
                    }
                }

                $expression = 'createControllerForm('.$action.', '.$definition.', controllerRuntime'.($parameters === [] ? '' : ', parameters').')';
                if ($options !== []) {
                    $context = [];
                    foreach ($options as $query) {
                        foreach ($query->options()['inputs'] as $reference) {
                            if ($reference['kind'] === 'context') {
                                $name = $reference['key'] ?? throw new RuntimeException('Missing option context key.');
                                $key = json_encode($name, JSON_THROW_ON_ERROR);
                                $context[$name] = $key.': parameters['.$key.']';
                            }
                        }
                    }

                    $expression = 'withOptionSources('.$expression.', _options_'.$method.', {'.implode(', ', $context).'})';
                }

                if ($parameters !== []) {
                    $expression = '(parameters: {'.implode('; ', $parameters).'}) => '.$expression;
                }

                $modules[$path][] = 'const _form_'.$method.' = '.$expression.';';
                $modules[$path][] = 'export {_form_'.$method.' as '.$method.'};';
            }

            foreach ($modules as $path => $lines) {
                $files[$path] = implode("\n", $lines)."\n";
            }

            if ($this->call('zero:generate', ['--react' => true]) !== self::SUCCESS) {
                return self::FAILURE;
            }

            (new GeneratedFiles($output, $enumPath))->publish($files);
            $this->info('Generated Formbraid definitions and Zero controller forms.');

            return self::SUCCESS;
        } catch (Throwable $throwable) {
            $this->error($throwable->getMessage());

            return self::FAILURE;
        }
    }

    private function operation(ControllerQuery $query): string
    {
        $name = json_encode($query->name(), JSON_THROW_ON_ERROR);
        $parse = resolve(SchemaDriver::class)->parse('_optionInputs['.$name.']', 'args');

        return '{inputs: '.json_encode((object) $query->options()['inputs'], JSON_THROW_ON_ERROR).', select: args => { try { return _optionBindings['.$name.']('.$parse.'); } catch { return undefined; } }}';
    }

    private function import(string $from, string $to): string
    {
        $directories = explode('/', dirname($from));
        $target = explode('/', substr($to, 0, -3));
        while ($directories !== [] && $target !== [] && $directories[0] === $target[0]) {
            array_shift($directories);
            array_shift($target);
        }

        $path = str_repeat('../', count($directories)).implode('/', $target);

        return json_encode(str_starts_with($path, '.') ? $path : './'.$path, JSON_THROW_ON_ERROR | JSON_UNESCAPED_SLASHES);
    }
}
